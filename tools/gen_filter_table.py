#!/usr/bin/env python3
"""Writes firmware/src/mello_filter_table.h: the main filter's biquad coefficients, as the HTML's Tone.Filter
(lowpass, rolloff -24: two identical BiquadFilterNodes) computes them.

  f = 80 * 200^cut  (logFilterHz),  Q = res * 15 dB  (Web Audio reads a lowpass Q in dB)
  w0 = 2 pi f / fs,  alpha = sin(w0) / (2 * 10^(Q/20))
  b0 = b2 = (1 - cos w0) / 2 / a0,  b1 = (1 - cos w0) / a0,  a1 = -2 cos w0 / a0,  a2 = (1 - alpha) / a0,
  a0 = 1 + alpha                                         (Web Audio spec, "BiquadFilterNode", lowpass)

cut 0..1 in 101 steps (0.01), res 0..1 in 21 steps (0.05); the engine interpolates between them. Q28.
Run: python3 tools/gen_filter_table.py"""
import math
from pathlib import Path

FS = 44100
CUTS, RESES = 101, 21
out = Path(__file__).resolve().parents[1] / "firmware" / "src" / "mello_filter_table.h"


def coeffs(cut, res):
    f = min(80 * 200 ** cut, FS / 2 * 0.999)
    w0 = 2 * math.pi * f / FS
    alpha = math.sin(w0) / (2 * 10 ** (res * 15 / 20))
    a0 = 1 + alpha
    c = math.cos(w0)
    q = lambda v: int(round(v / a0 * (1 << 28)))
    return q((1 - c) / 2), q(1 - c), q((1 - c) / 2), q(-2 * c), q(1 - alpha)


rows = []
for r in range(RESES):
    vals = [coeffs(i / (CUTS - 1), r / (RESES - 1)) for i in range(CUTS)]
    body = ",\n".join("        {%d, %d, %d, %d, %d}" % v for v in vals)
    rows.append("    { /* res %.2f */\n%s,\n    }," % (r / (RESES - 1), body))
# The FX tone filters (distTone, dlyTone, revTone): Tone.Filter lowpass -24, Q 0.2 dB, f from the HTML's
# helpers (lines 1143-1145), tone 0..1 in 101 steps.
FX = [("DIST_TONE_BIQUAD_Q28", 320, 38, "distToneHz"), ("DELAY_TONE_BIQUAD_Q28", 450, 26, "delayToneHz"),
      ("REVERB_TONE_BIQUAD_Q28", 700, 18, "reverbToneHz")]


def fx_coeffs(f):
    f = min(f, FS / 2 * 0.999)
    w0 = 2 * math.pi * f / FS
    alpha = math.sin(w0) / (2 * 10 ** (0.2 / 20))
    a0, c = 1 + alpha, math.cos(w0)
    q = lambda v: int(round(v / a0 * (1 << 28)))
    return q((1 - c) / 2), q(1 - c), q((1 - c) / 2), q(-2 * c), q(1 - alpha)


fx_text = ""
# The dedicated sub's filter: Tone.Filter lowpass -24, Q 0.8 dB, f = subFilterHz(t) = 40 * 55^t (line 1146).
vals = []
for i in range(101):
    f = min(40 * 55 ** (i / 100), FS / 2 * 0.999)
    w0 = 2 * math.pi * f / FS
    alpha = math.sin(w0) / (2 * 10 ** (0.8 / 20))
    a0, c = 1 + alpha, math.cos(w0)
    q = lambda v: int(round(v / a0 * (1 << 28)))
    vals.append((q((1 - c) / 2), q(1 - c), q((1 - c) / 2), q(-2 * c), q(1 - alpha)))
fx_text += "/* subFilterHz(t) = 40 * 55^t Hz, Q 0.8 dB: one biquad, used twice. */\n"
fx_text += "static const ToneSubBiquadCoeff SUB_FILTER_BIQUAD_Q28[101] = {\n%s,\n};\n" % ",\n".join(
    "    {%d, %d, %d, %d, %d}" % v for v in vals)
for name, base, ratio, helper in FX:
    vals = [fx_coeffs(base * ratio ** (i / 100)) for i in range(101)]
    body = ",\n".join("    {%d, %d, %d, %d, %d}" % v for v in vals)
    fx_text += f"/* {helper}(t) = {base} * {ratio}^t Hz, Q 0.2 dB: one biquad, used twice. */\n"
    fx_text += f"static const ToneSubBiquadCoeff {name}[101] = {{\n{body},\n}};\n"

text = f"""/* Generated by tools/gen_filter_table.py. Do not edit. */
/* The main filter as the HTML's Tone.Filter (lowpass, -24 dB/oct = two identical biquads), Web Audio's lowpass
 * formula with Q in dB: Q = res * 15 dB, f = 80 * 200^cut Hz, fs {FS}. [res step 0.05][cut step 0.01], Q28. */
#ifndef MELLO_FILTER_TABLE_H
#define MELLO_FILTER_TABLE_H
#define MAIN_FILTER_CUTS {CUTS}u
#define MAIN_FILTER_RESES {RESES}u
static const ToneSubBiquadCoeff MAIN_FILTER_BIQUAD_Q28[MAIN_FILTER_RESES][MAIN_FILTER_CUTS] = {{
{chr(10).join(rows)}
}};
{fx_text}#endif
"""
out.write_text(text)
print(f"wrote {out.relative_to(out.parents[2])}: {RESES} x {CUTS} main biquads, 4 x 101 sub and FX tone biquads")
