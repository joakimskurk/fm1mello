"""Writes firmware/src/mello_env_table.h: the per-sample decay coefficient of Tone.Envelope's exponential curves.

Tone 14 exponentialApproachValueAtTime(value, t, D): setTargetAtTime with tau = ln(D + 1) / ln(200), held at
t + 0.9 D, then a linear ramp to the value at t + D. Per sample the curve is level = target + (level - target) * c,
c = exp(-1 / (tau * fs)). Index: D in ms, 0..4000 (index 0 copies 1). Q31.
Run: python3 tools/gen_env_table.py"""
import math
from pathlib import Path

FS, MAX_MS = 44100, 4000
out = Path(__file__).resolve().parents[1] / "firmware" / "src" / "mello_env_table.h"


def coeff(ms):
    tau = math.log(max(ms, 1) / 1000 + 1) / math.log(200)
    return round(math.exp(-1 / (tau * FS)) * 2 ** 31)


vals = [coeff(ms) for ms in range(MAX_MS + 1)]
body = "\n".join("    " + ", ".join(f"{v}u" for v in vals[i:i + 8]) + "," for i in range(0, len(vals), 8))
out.write_text(f"""/* SPDX-License-Identifier: GPL-3.0-only */
/* Copyright (C) 2026 joakimskurk */
/* Generated by tools/gen_env_table.py. Do not edit. */
/* Tone.Envelope's exponential decay/release: per-sample coefficient for a segment of [ms], tau = ln(D+1)/ln 200,
 * fs {FS}, Q31. */
#ifndef MELLO_ENV_TABLE_H
#define MELLO_ENV_TABLE_H
#define TONE_ENV_MAX_MS {MAX_MS}u
static const uint32_t TONE_ENV_COEFF_Q31[TONE_ENV_MAX_MS + 1u] = {{
{body}
}};
#endif
""")
print(f"wrote {out.relative_to(out.parents[2])}: 0..{MAX_MS} ms")
