"""Writes tests/parity/stimuli.h from stimuli.json, so the C renderer plays exactly what the HTML renderer plays.
Run after editing stimuli.json: python3 tools/tone-ref/stimuli_to_c.py"""
import json
from pathlib import Path

here = Path(__file__).resolve().parent
spec = json.loads((here / "stimuli.json").read_text())
out = here.parent.parent / "tests" / "parity" / "stimuli.h"

FX = {"full": "STIM_FX_FULL", "dry": "STIM_FX_DRY", "reverb": "STIM_FX_REVERB"}
lines = [
    "/* SPDX-License-Identifier: GPL-3.0-only */",
    "/* Copyright (C) 2026 joakimskurk */",
    "/* Generated by tools/tone-ref/stimuli_to_c.py from tools/tone-ref/stimuli.json. Do not edit. */",
    "#ifndef STIMULI_H",
    "#define STIMULI_H",
    "",
    "typedef enum { STIM_FX_FULL, STIM_FX_DRY, STIM_FX_REVERB } StimFx;",
    "typedef struct { const char *key; const char *text; double num; } StimParam;",
    "typedef struct { double t, dur; int midi; double vel; int slide; } StimNote;",
    "typedef struct {",
    "    const char *name;",
    "    double seconds;",
    "    StimFx fx;",
    "    const StimParam *params;",
    "    int param_count;",
    "    const StimNote *lead;",
    "    int lead_count;",
    "    const StimNote *sub;",
    "    int sub_count;",
    "} Stimulus;",
    "",
    f"#define STIM_SAMPLE_RATE {spec['sample_rate']}",
    f"#define STIM_BPM {spec['bpm']}",
    "",
]
entries = []
for i, st in enumerate(spec["stimuli"]):
    params = st.get("params", {})
    plist = []
    for k, v in params.items():
        if isinstance(v, bool):
            plist.append(f'{{"{k}", 0, {1 if v else 0}}}')
        elif isinstance(v, str):
            plist.append(f'{{"{k}", "{v}", 0}}')
        else:
            plist.append(f'{{"{k}", 0, {v!r}}}')
    lines.append(f"static const StimParam stim{i}_params[] = {{{', '.join(plist) or '{0, 0, 0}'}}};")
    for voice in ("lead", "sub"):
        notes = st.get(voice, [])
        body = ", ".join(f"{{{n['t']!r}, {n['dur']!r}, {n['midi']}, {n.get('vel', 0.9)!r}, {int(n.get('slide', False))}}}"
                         for n in notes)
        lines.append(f"static const StimNote stim{i}_{voice}[] = {{{body or '{0, 0, 0, 0, 0}'}}};")
    entries.append(
        f'    {{"{st["name"]}", {st["seconds"]!r}, {FX[st["fx"]]}, stim{i}_params, {len(params)}, '
        f'stim{i}_lead, {len(st.get("lead", []))}, stim{i}_sub, {len(st.get("sub", []))}}},'
    )
lines += ["", "static const Stimulus STIMULI[] = {", *entries, "};", "#define STIM_COUNT ((int)(sizeof STIMULI / sizeof STIMULI[0]))", "", "#endif", ""]
out.write_text("\n".join(lines))
print(f"wrote {out.relative_to(here.parent.parent)} ({len(entries)} stimuli)")
